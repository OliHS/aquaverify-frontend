import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import {
  GLOSSARY_RETIRED_LEGACY_TERM_CANONICAL_IDS,
  GLOSSARY_STABLE_ID_OVERRIDES_BY_LEGACY_ID,
  GLOSSARY_TERM_ID_ALIASES,
  PROMOTED_GLOSSARY_TERM_IDS
} from '../utils/glossaryRelations.js';

const DEFAULT_SOURCE_PATH = 'utils/glossaryData.js';
const PACKAGE_ROOT = 'aquaverify_glosario_conocimiento_final_multilingue';
const OUTPUT_PATH = 'utils/glossaryData.js';
const ROUTES_OUTPUT_PATH = 'utils/glossaryRoutes.js';
const LANGUAGES = ['en', 'es', 'fr', 'it', 'ca'];

const HUB_PATHS = {
  en: '/en/glossary',
  es: '/es/glosario',
  fr: '/fr/glossaire',
  it: '/it/glossario',
  ca: '/ca/glossari'
};

function readZipEntry(zipPath, entryPath) {
  return execFileSync('unzip', ['-p', zipPath, entryPath], {
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024
  });
}

function normalizeLevel(value) {
  const normalized = String(value || '').trim().toLowerCase();
  if (['prioritario', 'priority', 'prioritaire', 'prioritari'].includes(normalized)) return 'priority';
  return 'supporting';
}

function normalizeTermId(value) {
  const normalized = String(value || '').trim();
  if (!normalized) return '';
  return GLOSSARY_TERM_ID_ALIASES[normalized] || normalized;
}

function stableTermIdForLegacyId(legacyId, englishTerm) {
  const numericId = Number(legacyId);
  if (GLOSSARY_RETIRED_LEGACY_TERM_CANONICAL_IDS[numericId]) {
    return GLOSSARY_RETIRED_LEGACY_TERM_CANONICAL_IDS[numericId];
  }
  if (GLOSSARY_STABLE_ID_OVERRIDES_BY_LEGACY_ID[numericId]) {
    return GLOSSARY_STABLE_ID_OVERRIDES_BY_LEGACY_ID[numericId];
  }
  return normalizeTermId(englishTerm?.slug || String(legacyId));
}

function normalizeTerm(term, index, englishTerm) {
  const legacyId = Number(term.legacyId ?? term.id ?? index);
  return {
    id: stableTermIdForLegacyId(legacyId, englishTerm),
    legacyId,
    term: term.term,
    slug: term.slug,
    category: term.category,
    categoryLabel: term.categoryLabel || term.category_label,
    definition: term.definition,
    application: term.application,
    product: term.product,
    sector: term.sector,
    keywords: Array.isArray(term.keywords) ? term.keywords : [],
    level: normalizeLevel(term.level),
    url: term.url
  };
}

async function loadTermsByLanguage(sourcePath) {
  if (sourcePath.endsWith('.zip')) {
    return Object.fromEntries(LANGUAGES.map((lang) => {
      const entry = `${PACKAGE_ROOT}/${lang}/json/aquaverify_glosario_terminos_${lang}.json`;
      return [lang, JSON.parse(readZipEntry(sourcePath, entry))];
    }));
  }

  if (sourcePath.endsWith('.json')) {
    const parsed = JSON.parse(await fs.readFile(sourcePath, 'utf8'));
    return parsed.GLOSSARY_TERMS || parsed.termsByLang || parsed;
  }

  const moduleUrl = pathToFileURL(`${process.cwd()}/${sourcePath}`).href;
  const module = await import(`${moduleUrl}?t=${Date.now()}`);
  return module.GLOSSARY_TERMS;
}

function unique(values) {
  const seen = new Set();
  return values.filter((value) => {
    if (!value || seen.has(value)) return false;
    seen.add(value);
    return true;
  });
}

const sourcePath = process.argv[2] || DEFAULT_SOURCE_PATH;
const rawTermsByLang = await loadTermsByLanguage(sourcePath);
const englishTerms = rawTermsByLang.en;

const termsByLang = Object.fromEntries(LANGUAGES.map((lang) => {
  const terms = rawTermsByLang[lang];
  if (!Array.isArray(terms) || terms.length !== englishTerms.length) {
    throw new Error(`Glossary source for ${lang} is missing or not aligned with English.`);
  }
  return [lang, terms.map((term, index) => normalizeTerm(term, index, englishTerms[index]))];
}));

const priorityIds = unique([
  ...termsByLang.es
    .filter((term) => term.level === 'priority')
    .map((term) => term.id),
  ...PROMOTED_GLOSSARY_TERM_IDS
]);

const legacyIdByStableId = new Map(
  termsByLang.en
    .filter((term) => !GLOSSARY_RETIRED_LEGACY_TERM_CANONICAL_IDS[term.legacyId])
    .map((term) => [term.id, term.legacyId])
);
const termRoutePaths = Object.fromEntries(priorityIds.map((id) => {
  const legacyId = legacyIdByStableId.get(id);
  if (legacyId === undefined) return null;
  return [
    `glossary-term-${id}`,
    Object.fromEntries(LANGUAGES.map((lang) => [lang, termsByLang[lang]?.[legacyId]?.url]).filter(([, url]) => Boolean(url)))
  ];
}).filter(Boolean));

const output = [
  '// Generated by scripts/generate-glossary-data.js. Do not edit by hand.',
  `export const GLOSSARY_TERMS = ${JSON.stringify(termsByLang, null, 2)};`
].join('\n\n');

const routesOutput = [
  '// Generated by scripts/generate-glossary-data.js. Do not edit by hand.',
  `export const GLOSSARY_LANGUAGES = ${JSON.stringify(LANGUAGES)};`,
  `export const GLOSSARY_HUB_PATHS = ${JSON.stringify(HUB_PATHS, null, 2)};`,
  `export const GLOSSARY_PRIORITY_IDS = ${JSON.stringify(priorityIds, null, 2)};`,
  `export const GLOSSARY_TERM_ROUTE_PATHS = ${JSON.stringify(termRoutePaths, null, 2)};`
].join('\n\n');

await fs.writeFile(OUTPUT_PATH, `${output}\n`);
await fs.writeFile(ROUTES_OUTPUT_PATH, `${routesOutput}\n`);
console.log(`Generated ${OUTPUT_PATH} and ${ROUTES_OUTPUT_PATH} with ${priorityIds.length} priority terms per language from ${sourcePath}.`);
