import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';

const DEFAULT_ZIP_PATH = '/Users/prismadual/Downloads/aquaverify_glosario_conocimiento_final_multilingue_package.zip';
const PACKAGE_ROOT = 'aquaverify_glosario_conocimiento_final_multilingue';
const OUTPUT_PATH = 'utils/glossaryData.js';
const ROUTES_OUTPUT_PATH = 'utils/glossaryRoutes.js';
const LANGUAGES = ['en', 'es', 'fr', 'it', 'ca'];

const HUB_PATHS = {
  en: '/en/glossary',
  es: '/es/glosario',
  fr: '/fr/glossaire',
  it: '/it/glossario',
  ca: '/ca/glossari'
};

function readZipEntry(zipPath, entryPath) {
  return execFileSync('unzip', ['-p', zipPath, entryPath], {
    encoding: 'utf8',
    maxBuffer: 10 * 1024 * 1024
  });
}

function normalizeLevel(value) {
  const normalized = String(value || '').trim().toLowerCase();
  if (['prioritario', 'priority', 'prioritaire', 'prioritari'].includes(normalized)) return 'priority';
  return 'supporting';
}

function normalizeTerm(term, index) {
  return {
    id: index,
    term: term.term,
    slug: term.slug,
    category: term.category,
    categoryLabel: term.category_label,
    definition: term.definition,
    application: term.application,
    product: term.product,
    sector: term.sector,
    keywords: Array.isArray(term.keywords) ? term.keywords : [],
    level: normalizeLevel(term.level),
    url: term.url
  };
}

const zipPath = process.argv[2] || DEFAULT_ZIP_PATH;
const termsByLang = {};

for (const lang of LANGUAGES) {
  const entry = `${PACKAGE_ROOT}/${lang}/json/aquaverify_glosario_terminos_${lang}.json`;
  const terms = JSON.parse(readZipEntry(zipPath, entry));
  termsByLang[lang] = terms.map(normalizeTerm);
}

const priorityIds = termsByLang.es
  .filter((term) => term.level === 'priority')
  .map((term) => term.id);

const termRoutePaths = Object.fromEntries(priorityIds.map((id) => [
  `glossary-term-${id}`,
  Object.fromEntries(LANGUAGES.map((lang) => [lang, termsByLang[lang]?.[id]?.url]).filter(([, url]) => Boolean(url)))
]));

const output = [
  '// Generated by scripts/generate-glossary-data.js. Do not edit by hand.',
  `export const GLOSSARY_TERMS = ${JSON.stringify(termsByLang, null, 2)};`,
].join('\n\n');

const routesOutput = [
  '// Generated by scripts/generate-glossary-data.js. Do not edit by hand.',
  `export const GLOSSARY_LANGUAGES = ${JSON.stringify(LANGUAGES)};`,
  `export const GLOSSARY_HUB_PATHS = ${JSON.stringify(HUB_PATHS, null, 2)};`,
  `export const GLOSSARY_PRIORITY_IDS = ${JSON.stringify(priorityIds)};`,
  `export const GLOSSARY_TERM_ROUTE_PATHS = ${JSON.stringify(termRoutePaths, null, 2)};`
].join('\n\n');

await fs.writeFile(OUTPUT_PATH, `${output}\n`);
await fs.writeFile(ROUTES_OUTPUT_PATH, `${routesOutput}\n`);
console.log(`Generated ${OUTPUT_PATH} and ${ROUTES_OUTPUT_PATH} with ${priorityIds.length} priority terms per language.`);
